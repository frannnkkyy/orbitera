using Orbitera.Domain;

namespace Orbitera.Domain.Tests;

public sealed class CleanupPlanSimulatorTests
{
    [Theory]
    [InlineData(200, 450)]
    [InlineData(900, 1_000)]
    public void ProjectsAvailableSpaceWithoutExceedingCapacity(long availableBytes, long expectedAfterBytes)
    {
        var plan = CreatePlan(250);

        var simulation = CleanupPlanSimulator.Simulate(plan, 1_000, availableBytes);

        Assert.Equal(250, simulation.EstimatedRecoverableBytes);
        Assert.Equal(availableBytes, simulation.AvailableBeforeBytes);
        Assert.Equal(expectedAfterBytes, simulation.ProjectedAvailableBytes);
        Assert.True(plan.IsReadOnly);
    }

    [Fact]
    public void LeavesProjectedSpaceUnknownWhenCapacityEvidenceIsUnavailable()
    {
        var simulation = CleanupPlanSimulator.Simulate(CreatePlan(250), null, null);

        Assert.Null(simulation.AvailableBeforeBytes);
        Assert.Null(simulation.ProjectedAvailableBytes);
    }

    private static CleanupPlan CreatePlan(long bytes)
    {
        var candidate = new DevelopmentInsightRecommendation(
            "app",
            @"C:\workspace\app",
            "bin",
            @"C:\workspace\app\bin",
            bytes,
            DevelopmentEcosystem.DotNet,
            DevelopmentInsightCategory.BuildArtifact,
            DevelopmentRiskLevel.Low,
            true,
            "Generated build output.",
            "It can be regenerated by building again.");

        return CleanupPlanFactory.Create([candidate], [candidate.DirectoryPath]);
    }
}
